    #[test]
    fn helper_functions_cover_edge_cases() {
        let (metadata, body) = parse_frontmatter("---\nname: test\ndescription: hi\n---\n\nBody\n");
        assert_eq!(metadata.get("name").unwrap(), "test");
        assert!(body.contains("Body"));

        let (metadata, body) = parse_frontmatter("No frontmatter");
        assert!(metadata.is_empty());
        assert_eq!(body, "No frontmatter");

        let inserted = replace_or_append_block(
            "",
            "profile=x;tool=codex",
            "<!-- skill-reader:begin profile=x;tool=codex -->\nbody\n<!-- skill-reader:end profile=x;tool=codex -->",
        );
        assert!(inserted.contains("body"));

        let replaced = replace_or_append_block(
            &inserted,
            "profile=x;tool=codex",
            "<!-- skill-reader:begin profile=x;tool=codex -->\nnext\n<!-- skill-reader:end profile=x;tool=codex -->",
        );
        assert!(replaced.contains("next"));
        assert!(!replaced.contains("\nbody\n"));

        let removed = remove_block(&replaced, "profile=x;tool=codex");
        assert!(!removed.contains("next"));

        assert_eq!(capitalize("skill"), "Skill");
        assert_eq!(capitalize(""), "");
        assert!(generated_comment("p", ProfileTool::Codex).contains(GENERATED_PREFIX));
        assert_eq!(expand_home("/tmp/x"), PathBuf::from("/tmp/x"));
    }

